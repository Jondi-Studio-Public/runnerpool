def test_no_credential_at_all_fails(box):
    r = box.sh("gh_api GET 'orgs/example-org/actions/runners?per_page=1' || true; echo kind=$(credential_kind)")
    assert "kind=none" in r.stdout and "no GitHub credential" in r.stderr
