@pytest.mark.parametrize("workflow", ["admin.yml", "admin-win.yml"])
def test_admin_workflows_offer_set_app_and_never_echo_the_key(workflow):
    text = (ROOT / ".github" / "workflows" / workflow).read_text()
    assert "- set-app" in text and "- rotate-token" in text  # rotate-token keeps working for the PAT
    assert "secrets.CI_APP_ID" in text and "secrets.CI_APP_PRIVATE_KEY" in text
    # the key's secret is only ever handed to the step as an environment variable, and never printed
    assert [ln.strip() for ln in text.splitlines() if "secrets.CI_APP_PRIVATE_KEY" in ln] == [
        "APP_PRIVATE_KEY: ${{ inputs.action == 'set-app' && secrets.CI_APP_PRIVATE_KEY || '' }}"
    ]
    for ln in text.splitlines():
        if "APP_PRIVATE_KEY" in ln or "NEW_APP_KEY_B64" in ln:
            assert not any(w in ln for w in ('echo "$', 'Write-Host "$', "echo $", "Write-Host $env"))
