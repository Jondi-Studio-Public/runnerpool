def test_status_line_names_the_credential(box):
    r = box.sh("credential_line example-org")
    assert r.stdout.strip().startswith("none")
    box.install_pat()
    # the PAT's expiry comes from a response header the stand-in does not send: "never"
    assert box.sh("credential_line example-org").stdout.strip() == "GitHub token stored, expires never"
    box.install_app()
    assert box.sh("credential_line example-org").stdout.strip() == f"GitHub App 12345, token valid until {ISO}"
    box.flag("no_token")
    (box.home / "github-app-token.expires").unlink()
    assert "no token can be minted" in box.sh("credential_line example-org").stdout


def test_set_app_stores_checks_and_replaces_the_pat(box):
    box.install_pat("pat123")
    r = box.set_app()
    assert r.returncode == 0, r.stdout + r.stderr
    assert "now mints GitHub App tokens (App 12345" in r.stdout
    assert not (box.home / "github-auth.header").exists()
    assert (box.home / "github-app.id").read_text().strip() == "12345"
    pem = box.home / "github-app.pem"
    assert pem.read_bytes() == box.keys["pkcs1"].read_bytes()
    assert stat.S_IMODE(pem.stat().st_mode) == 0o600
    assert box.minted() == 1
    # nothing secret in the output
    assert "BEGIN" not in r.stdout + r.stderr and "ghs_FAKE" not in r.stdout + r.stderr
    assert list(box.home.glob(".cred.*")) == [] and list(box.home.glob(".app.*")) == []


def test_set_app_failure_brings_the_old_pat_back(box):
    box.install_pat("pat123")
    box.flag("list_fails")  # the new App can mint but cannot list the runners
    r = box.set_app()
    assert r.returncode != 0 and "kept the old credential" in r.stderr
    assert (box.home / "github-auth.header").read_text() == "Authorization: Bearer pat123\n"
    assert sorted(p.name for p in box.home.iterdir()) == ["github-auth.header"]


def test_set_app_failure_brings_the_old_app_back(box):
    box.install_app(app_id="111", key="pkcs8")
    box.sh("app_ensure")
    before = {p.name: p.read_bytes() for p in box.home.iterdir()}
    box.flag("no_token")
    r = box.set_app(app_id="222")
    assert r.returncode != 0
    assert {p.name: p.read_bytes() for p in box.home.iterdir()} == before


def test_set_app_rejects_a_key_that_is_not_pem(box):
    box.install_pat()
    r = box.cli("set-app", "example-org", NEW_APP_ID="1", NEW_APP_KEY_B64=base64.b64encode(b"not a key").decode())
    assert r.returncode != 0
    assert (box.home / "github-auth.header").exists() and not (box.home / "github-app.pem").exists()
    r = box.cli("set-app", "example-org")
    assert r.returncode != 0 and "NEW_APP_ID" in r.stderr


def test_set_token_switches_an_app_device_back_to_a_pat_and_restores_on_failure(box):
    box.install_app()
    box.sh("app_ensure")
    r = box.cli("set-token", "example-org", NEW_GITHUB_TOKEN="newpat")
    assert r.returncode == 0, r.stderr
    assert (box.home / "github-auth.header").read_text() == "Authorization: Bearer newpat\n"
    assert not (box.home / "github-app.pem").exists() and not (box.home / "github-app-token.header").exists()
    assert "Bearer newpat" in box.calls()[-1]  # verified with the PAT, not the App

    box2 = box.t / "second"
    box2.mkdir()
    b = Box(box2, box.keys)
    b.install_app()
    b.sh("app_ensure")
    before = {p.name: p.read_bytes() for p in b.home.iterdir()}
    b.flag("list_fails")
    r = b.cli("set-token", "example-org", NEW_GITHUB_TOKEN="badpat")
    assert r.returncode != 0 and "kept the old credential" in r.stderr
    assert {p.name: p.read_bytes() for p in b.home.iterdir()} == before


